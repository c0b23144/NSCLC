def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    print("===== CT-condition x HU-cluster IoU analysis =====")

    print("HU解析結果を読み込みます...")
    df_hu = load_hu_data()

    print("\nHU CSV split counts:")
    print(df_hu.groupby("split").size())

    print("\nHU CSV cluster counts:")
    print(df_hu.groupby(["split", "cluster"]).size())

    device = torch.device(
        "cuda" if torch.cuda.is_available() else "cpu"
    )
    print(f"\nDevice: {device}")

    all_results = []

    for ct_mode in CT_MODES:
        if ct_mode not in CT_SETTINGS:
            raise ValueError(f"CT_SETTINGSに存在しない条件: {ct_mode}")

        print(f"\n========== CT mode: {ct_mode} ==========")

        if not os.path.exists(WEIGHTS[ct_mode]):
            warnings.warn(
                f"{ct_mode} の重みがないためスキップします: "
                f"{WEIGHTS[ct_mode]}"
            )
            continue

        for split in ["train", "test"]:
            results = evaluate_one_mode(
                ct_mode,
                split,
                df_hu,
                device,
            )
            all_results.extend(results)

    if not all_results:
        raise RuntimeError(
            "評価結果がありません。重み・画像パス・HU CSVを確認してください。"
        )

    results_df = pd.DataFrame(all_results)

    merged, summary = save_csv_outputs(results_df, df_hu)

    print("\n===== Cluster IoU summary =====")
    print(summary.to_string(index=False))

    print("\nIoU plots...")
    plot_iou_boxplots(merged)
    plot_iou_histograms(merged)

    print("\nLow-IoU HU density curves...")
    for split in ["train", "test"]:
        clusters = sorted(
            merged.loc[merged["split"] == split, "cluster"]
            .dropna()
            .unique()
        )

        for cluster in clusters:
            plot_density_curves(
                merged=merged,
                split=split,
                cluster=int(cluster),
                output_name=(
                    f"low_iou_hu_density_{split}_cluster{cluster}.png"
                ),
                title=(
                    f"Lowest IoU HU density: "
                    f"{split} / Cluster {cluster}"
                ),
                max_curves=LOW_IOU_N,
            )

    print("\nTest Cluster 1: all HU density curves...")
    plot_test_cluster1_all(merged)

    print("\n===== Finished =====")
    print(f"Output directory: {OUTPUT_DIR}")
    print("Created files:")
    for filename in sorted(os.listdir(OUTPUT_DIR)):
        print(" -", filename)


if __name__ == "__main__":
    main()
    