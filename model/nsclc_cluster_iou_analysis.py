"""
NSCLC: CT-condition models x HU-density clusters IoU analysis

- CT modes: lung / mediastinal / raw
- Existing Train/Test and cluster assignments are read from slice_stats.csv.
- No new train/test split is performed.
- Train: all tumor-positive slices
- Test: one maximum-tumor-area slice per patient
- IoU is calculated on the 512x512 resized masks, matching model evaluation.
"""

import os
import gc
import re
import warnings

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import torch
from torch.utils.data import DataLoader

from TransAttUnet import UNet_Attention_Transformer_Multiscale
from Nsclc_train_ct import (
    NSCLCSliceDataset,
    IMAGES_DIR,
    LABELS_DIR,
    TARGET_SIZE,
    CT_SETTINGS,
)

# =========================================================
# Settings
# =========================================================

HU_ROOT = "output/hu_density_analysis"
HU_CSV = os.path.join(HU_ROOT, "slice_stats.csv")
DENSITY_FILES = {
    "train": os.path.join(HU_ROOT, "densities_train.npy"),
    "test": os.path.join(HU_ROOT, "densities_test.npy"),
}

OUTPUT_DIR = "output/cluster_iou_analysis_ct"

CT_MODES = ["lung", "mediastinal", "raw"]

WEIGHTS = {
    "lung": "checkpoints_ct/lung/model_epoch_250.pth",
    "mediastinal": "checkpoints_ct/mediastinal/model_epoch_250.pth",
    "raw": "checkpoints_ct/raw/model_epoch_250.pth",
}

BATCH_SIZE = 8
NUM_WORKERS = 0
LOW_IOU_N = 5

# HU density histogram settings must match nsclc_hu_density.py
HU_MIN = -1000
HU_MAX = 400
HU_BIN = 10
HU_CENTERS = (np.arange(HU_MIN, HU_MAX + HU_BIN, HU_BIN)[:-1]
              + HU_BIN / 2)


# =========================================================
# Utility
# =========================================================

def normalize_case_name(value):
    """Normalize a case filename while preserving its case ID."""
    name = os.path.basename(str(value))
    if name.endswith(".nii.gz"):
        return name
    return name + ".nii.gz"


def load_model_weights(model, path, device):
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"重みファイルが見つかりません: {path}"
        )

    state = torch.load(path, map_location=device)

    if isinstance(state, dict) and "model_state_dict" in state:
        state = state["model_state_dict"]

    state = {
        k.replace("module.", "", 1): v
        for k, v in state.items()
    }
    model.load_state_dict(state)


def calculate_iou(pred, target):
    """Calculate binary IoU. Both arrays must have the same shape."""
    pred = np.asarray(pred, dtype=bool)
    target = np.asarray(target, dtype=bool)

    intersection = np.logical_and(pred, target).sum()
    union = np.logical_or(pred, target).sum()

    # Both masks empty: define IoU as 1.
    if union == 0:
        return 1.0

    return float(intersection / union)


def load_hu_data():
    if not os.path.exists(HU_CSV):
        raise FileNotFoundError(
            f"{HU_CSV} がありません。先に nsclc_hu_density.py を実行してください。"
        )

    df = pd.read_csv(HU_CSV)

    required = {"split", "case", "slice", "cluster"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(
            f"slice_stats.csv に必要な列がありません: {sorted(missing)}"
        )

    df["case"] = df["case"].map(normalize_case_name)
    df["slice"] = df["slice"].astype(int)
    df["cluster"] = df["cluster"].astype(int)
    df["split"] = df["split"].astype(str).str.lower()

    return df


def make_pairs(df, split):
    """Create image/label pairs using cases already present in HU CSV."""
    cases = sorted(df.loc[df["split"] == split, "case"].unique())

    pairs = []
    for case in cases:
        image_path = os.path.join(IMAGES_DIR, case)
        label_path = os.path.join(LABELS_DIR, case)

        if not os.path.exists(image_path):
            warnings.warn(f"画像がありません: {image_path}")
            continue

        if not os.path.exists(label_path):
            warnings.warn(f"ラベルがありません: {label_path}")
            continue

        pairs.append({
            "image": image_path,
            "label": label_path,
            "name": case,
        })

    return pairs


def build_expected_keys(df, split):
    """
    HU CSV keys define exactly which slices are included in this analysis.

    Train: all rows.
    Test: one row per patient, as generated by TEST_MODE='max'.
    """
    part = df[df["split"] == split].copy()

    if split == "test":
        duplicated = part["case"].duplicated(keep=False)
        if duplicated.any():
            warnings.warn(
                "Test CSVに同一症例の複数行があります。"
                "tumor_size最大の行を使用します。"
            )
            part = (
                part.sort_values("tumor_size", ascending=False)
                .drop_duplicates("case", keep="first")
            )

    return {
        (row.case, int(row.slice))
        for row in part.itertuples()
    }


def make_test_slice_lookup(df):
    """Map test patient filename to the maximum-slice index in HU CSV."""
    part = df[df["split"] == "test"].copy()

    if "tumor_size" in part.columns:
        part = (
            part.sort_values("tumor_size", ascending=False)
            .drop_duplicates("case", keep="first")
        )
    else:
        part = part.drop_duplicates("case")

    return {
        row.case: int(row.slice)
        for row in part.itertuples()
    }


