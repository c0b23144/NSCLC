def plot_iou_boxplots(merged):
    for split in ["train", "test"]:
        part = merged[merged["split"] == split]
        if part.empty:
            continue

        clusters = sorted(part["cluster"].dropna().unique())

        fig, axes = plt.subplots(
            1,
            max(1, len(clusters)),
            figsize=(6 * max(1, len(clusters)), 5),
            squeeze=False,
        )

        for ax, cluster in zip(axes.ravel(), clusters):
            sub = part[part["cluster"] == cluster]

            data = [
                sub.loc[sub["ct_mode"] == mode, "IoU"].dropna().values
                for mode in CT_MODES
            ]

            ax.boxplot(
                data,
                labels=CT_MODES,
                showmeans=True,
            )
            ax.set_title(f"{split.upper()} / Cluster {cluster}")
            ax.set_ylabel("IoU")
            ax.set_ylim(-0.05, 1.05)
            ax.grid(axis="y", alpha=0.3)

        plt.tight_layout()
        plt.savefig(
            os.path.join(OUTPUT_DIR, f"iou_boxplot_{split}.png"),
            dpi=200,
        )
        plt.close()


def plot_iou_histograms(merged):
    for split in ["train", "test"]:
        part = merged[merged["split"] == split]
        if part.empty:
            continue

        for cluster in sorted(part["cluster"].dropna().unique()):
            sub = part[part["cluster"] == cluster]

            plt.figure(figsize=(7, 5))

            for mode in CT_MODES:
                values = sub.loc[
                    sub["ct_mode"] == mode, "IoU"
                ].dropna()

                if len(values):
                    plt.hist(
                        values,
                        bins=np.linspace(0, 1, 21),
                        alpha=0.4,
                        label=mode,
                    )

            plt.xlabel("IoU")
            plt.ylabel("Number of slices")
            plt.title(f"IoU distribution: {split} / Cluster {cluster}")
            plt.legend()
            plt.grid(alpha=0.25)
            plt.tight_layout()
            plt.savefig(
                os.path.join(
                    OUTPUT_DIR,
                    f"iou_hist_{split}_cluster{cluster}.png",
                ),
                dpi=200,
            )
            plt.close()


