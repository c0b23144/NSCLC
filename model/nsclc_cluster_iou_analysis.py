# Evaluation
# =========================================================

def evaluate_one_mode(ct_mode, split, df_hu, device):
    """
    Evaluate one CT condition and one split.

    The dataset implementation and preprocessing are imported from
    Nsclc_train_ct.py to keep consistency with model training.
    """
    split_df = df_hu[df_hu["split"] == split].copy()
    if split_df.empty:
        print(f"[{ct_mode}/{split}] 対象データがありません。")
        return []

    pairs = make_pairs(df_hu, split)
    if not pairs:
        print(f"[{ct_mode}/{split}] 画像・ラベルペアがありません。")
        return []

    mode = "all" if split == "train" else "max"

    dataset = NSCLCSliceDataset(
        pairs,
        ct_mode,
        mode=mode,
        target_size=TARGET_SIZE,
    )

    if len(dataset) == 0:
        print(f"[{ct_mode}/{split}] Datasetが空です。")
        return []

    loader = DataLoader(
        dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=NUM_WORKERS,
    )

    model = UNet_Attention_Transformer_Multiscale(
        n_channels=1,
        n_classes=1,
    ).to(device)

    weight_path = WEIGHTS[ct_mode]
    load_model_weights(model, weight_path, device)
    model.eval()

    # HU CSV determines which slices are retained in the analysis.
    expected_keys = build_expected_keys(df_hu, split)
    test_slice_lookup = (
        make_test_slice_lookup(df_hu) if split == "test" else {}
    )

    results = []
    dataset_index = 0

    with torch.no_grad():
        for images, masks, names, tumor_sizes in loader:
            images = images.to(device)
            outputs = model(images)

            predictions = (
                torch.sigmoid(outputs) > 0.5
            ).cpu().numpy()

            targets = masks.numpy() > 0.5

            for i in range(len(names)):
                meta = dataset.meta[dataset_index]
                dataset_index += 1

                raw_name = str(names[i])

                if split == "train":
                    # Dataset name format:
                    # patient.nii.gz_slice123
                    match = re.match(r"^(.*\.nii\.gz)_slice(\d+)$", raw_name)
                    if match is None:
                        warnings.warn(
                            f"Trainスライス名を解析できません: {raw_name}"
                        )
                        continue

                    case = normalize_case_name(match.group(1))
                    slice_index = int(match.group(2))

                else:
                    case = normalize_case_name(raw_name)

                    if case not in test_slice_lookup:
                        continue

                    slice_index = test_slice_lookup[case]

                key = (case, slice_index)

                # Exclude slices not present in HU analysis CSV.
                if key not in expected_keys:
                    continue

                iou = calculate_iou(
                    predictions[i, 0],
                    targets[i, 0],
                )

                results.append({
                    "ct_mode": ct_mode,
                    "split": split,
                    "case": case,
                    "slice": slice_index,
                    "tumor_size": int(tumor_sizes[i]),
                    "IoU": iou,
                })

    del model, dataset, loader
    gc.collect()

    if device.type == "cuda":
        torch.cuda.empty_cache()

    print(
        f"[{ct_mode}/{split}] "
        f"評価結果: {len(results)} slices"
    )

    return results


# =========================================================
# CSV outputs
# =========================================================

def save_csv_outputs(results_df, df_hu):
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    results_df.to_csv(
        os.path.join(OUTPUT_DIR, "case_iou.csv"),
        index=False,
    )

    merged = results_df.merge(
        df_hu[["split", "case", "slice", "cluster"]],
        on=["split", "case", "slice"],
        how="left",
        validate="many_to_one",
    )

    merged.to_csv(
        os.path.join(OUTPUT_DIR, "case_iou_with_cluster.csv"),
        index=False,
    )

    summary = (
        merged.groupby(["ct_mode", "split", "cluster"])["IoU"]
        .agg(["count", "mean", "std", "median", "min", "max"])
        .reset_index()
        .rename(columns={"count": "n"})
    )

    summary.to_csv(
        os.path.join(OUTPUT_DIR, "cluster_iou_summary.csv"),
        index=False,
    )

    return merged, summary


