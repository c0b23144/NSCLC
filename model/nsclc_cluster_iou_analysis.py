def load_density_data(split):
    path = DENSITY_FILES[split]

    if not os.path.exists(path):
        raise FileNotFoundError(
            f"HU密度ファイルがありません: {path}"
        )

    density = np.load(path)
    df = pd.read_csv(HU_CSV)

    df["case"] = df["case"].map(normalize_case_name)
    df["slice"] = df["slice"].astype(int)
    df["split"] = df["split"].astype(str).str.lower()

    # The original HU script creates density arrays and CSV rows
    # in the same order. Keep that row order here.
    part = df[df["split"] == split].reset_index(drop=True)

    if len(part) != len(density):
        raise ValueError(
            f"{split}: slice_stats.csv rows ({len(part)}) "
            f"と density rows ({len(density)}) が一致しません。"
            "HU解析時のCSVとnpyが同じ実行結果か確認してください。"
        )

    part["density_index"] = np.arange(len(part))

    return part, density


def plot_density_curves(
    merged,
    split,
    cluster,
    output_name,
    title,
    max_curves=None,
):
    hu_df, density = load_density_data(split)

    # IoU is averaged across CT modes for ranking the HU curves.
    iou_part = merged[
        (merged["split"] == split)
        & (merged["cluster"] == cluster)
    ]

    if iou_part.empty:
        print(f"[密度図] {split} Cluster {cluster}: IoUデータなし")
        return

    ranked = (
        iou_part.groupby(["case", "slice"])["IoU"]
        .mean()
        .reset_index()
        .sort_values("IoU", ascending=True)
    )

    selected = hu_df[
        (hu_df["cluster"] == cluster)
    ].merge(
        ranked,
        on=["case", "slice"],
        how="inner",
    ).sort_values("IoU", ascending=True)

    if max_curves is not None:
        selected = selected.head(max_curves)

    if selected.empty:
        print(f"[密度図] {split} Cluster {cluster}: 対象スライスなし")
        return

    plt.figure(figsize=(10, 6))

    for row in selected.itertuples():
        idx = int(row.density_index)
        plt.plot(
            HU_CENTERS,
            density[idx],
            linewidth=1.0,
            alpha=0.65,
            label=(
                f"{row.case.replace('.nii.gz', '')}"
                f" z{row.slice} IoU={row.IoU:.3f}"
            ),
        )

    plt.xlabel("HU")
    plt.ylabel("Probability density")
    plt.title(title)
    plt.grid(alpha=0.25)
    plt.legend(
        fontsize=7,
        bbox_to_anchor=(1.02, 1),
        loc="upper left",
    )
    plt.tight_layout()
    plt.savefig(
        os.path.join(OUTPUT_DIR, output_name),
        dpi=200,
        bbox_inches="tight",
    )
    plt.close()


def plot_test_cluster1_all(merged):
    """
    Plot every Test Cluster 1 HU density curve.
    The HU CSV is the source of cluster membership.
    """
    hu_df, density = load_density_data("test")

    selected = hu_df[hu_df["cluster"] == 1].copy()

    if selected.empty:
        print("Test Cluster 1 は0件です。")
        return

    # Add mean IoU across available CT modes for the legend.
    iou_part = merged[
        (merged["split"] == "test")
        & (merged["cluster"] == 1)
    ]

    mean_iou = (
        iou_part.groupby(["case", "slice"])["IoU"]
        .mean()
        .to_dict()
    )

    plt.figure(figsize=(12, 7))

    for row in selected.itertuples():
        idx = int(row.density_index)
        key = (row.case, int(row.slice))
        iou_text = (
            f"IoU={mean_iou[key]:.3f}"
            if key in mean_iou else "IoU=N/A"
        )

        plt.plot(
            HU_CENTERS,
            density[idx],
            linewidth=1.0,
            alpha=0.65,
            label=(
                f"{row.case.replace('.nii.gz', '')} "
                f"z{row.slice} {iou_text}"
            ),
        )

    plt.xlabel("HU")
    plt.ylabel("Probability density")
    plt.title(
        f"Test Cluster 1: all HU density curves (n={len(selected)})"
    )
    plt.grid(alpha=0.25)
    plt.legend(
        fontsize=6,
        bbox_to_anchor=(1.02, 1),
        loc="upper left",
    )
    plt.tight_layout()
    plt.savefig(
        os.path.join(
            OUTPUT_DIR,
            "cluster1_test_all_hu_density.png",
        ),
        dpi=200,
        bbox_inches="tight",
    )
    plt.close()


